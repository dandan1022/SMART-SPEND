"""Small DB-API compatibility layer for the existing SQLite-style SQL statements.

Used only if DATABASE_URL is configured. PostgreSQL stores the permanent data;
no credentials are saved in source code. Requires psycopg 3.
"""
import re
from decimal import Decimal
from psycopg import connect
from psycopg.rows import dict_row

class Row(dict):
    def __init__(self, row):
        # PostgreSQL SUM(bigint) uses numeric/Decimal; JSON responses expect
        # ordinary numbers, just as sqlite3 returns them.
        super().__init__({k: (int(v) if v == v.to_integral_value() else float(v))
                          if isinstance(v, Decimal) else v for k, v in row.items()})
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)

class Cursor:
    def __init__(self, cursor, lastrowid=None):
        self.cursor = cursor
        self.lastrowid = lastrowid
    def fetchone(self):
        r = self.cursor.fetchone()
        return Row(r) if r is not None else None
    def fetchall(self):
        return [Row(r) for r in self.cursor.fetchall()]
    def __iter__(self):
        return (Row(r) for r in self.cursor)

class Connection:
    def __init__(self, url):
        self.raw = connect(url, row_factory=dict_row, connect_timeout=12)
    def execute(self, sql, args=None):
        # SQLite uses '?' for SQL parameters; psycopg uses '%s'.
        sql = sql.replace('?', '%s')
        sql = re.sub(r'\bsubstr\s*\(', 'substring(', sql, flags=re.I)
        # Some existing inserts need sqlite's cursor.lastrowid behavior.
        # Avoid touching inserts with ON CONFLICT and other SQL.
        make_id = bool(re.match(r'\s*INSERT\s+INTO\s+(users|transactions|predictions|imports)\b', sql, re.I))
        if make_id and 'RETURNING' not in sql.upper():
            sql += ' RETURNING id'
        cur = self.raw.cursor()
        cur.execute(sql, args or ())
        result_id = None
        if make_id:
            result_id = cur.fetchone()['id']
        return Cursor(cur, result_id)
    def executemany(self, sql, seq):
        sql = sql.replace('?', '%s')
        with self.raw.cursor() as cur:
            cur.executemany(sql, seq)
    def commit(self): self.raw.commit()
    def rollback(self): self.raw.rollback()
    def close(self): self.raw.close()

POSTGRES_SCHEMA = '''
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT (to_char(now() at time zone 'UTC','YYYY-MM-DD HH24:MI:SS'))
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower ON users (lower(email));
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
 role TEXT NOT NULL CHECK(role IN ('user','admin')),
 csrf TEXT NOT NULL, expires_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 date TEXT NOT NULL, description TEXT NOT NULL, category TEXT NOT NULL,
 kind TEXT NOT NULL CHECK(kind IN ('expense','income')),
 amount_cents BIGINT NOT NULL CHECK(amount_cents>0), source TEXT NOT NULL DEFAULT 'manual',
 created_at TEXT NOT NULL DEFAULT (to_char(now() at time zone 'UTC','YYYY-MM-DD HH24:MI:SS'))
);
CREATE INDEX IF NOT EXISTS idx_transactions_user_date ON transactions(user_id,date);
CREATE TABLE IF NOT EXISTS budgets (
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 month TEXT NOT NULL, amount_cents BIGINT NOT NULL CHECK(amount_cents>=0),
 PRIMARY KEY (user_id,month)
);
CREATE TABLE IF NOT EXISTS predictions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 forecast_month TEXT NOT NULL, predicted_cents BIGINT NOT NULL,
 model TEXT NOT NULL, mae DOUBLE PRECISION NOT NULL, rmse DOUBLE PRECISION NOT NULL,
 metadata_json TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT (to_char(now() at time zone 'UTC','YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS imports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 filename TEXT NOT NULL, imported INTEGER NOT NULL, duplicates INTEGER NOT NULL,
 invalid INTEGER NOT NULL, outliers INTEGER NOT NULL,
 created_at TEXT NOT NULL DEFAULT (to_char(now() at time zone 'UTC','YYYY-MM-DD HH24:MI:SS'))
);
'''

def setup(url):
    conn = connect(url, connect_timeout=12)
    try:
        with conn.cursor() as cur:
            for sql in POSTGRES_SCHEMA.split(';'):
                if sql.strip(): cur.execute(sql)
        conn.commit()
    finally:
        conn.close()